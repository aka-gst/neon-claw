/**
 * Счётчик. Четыре точки выхода, ничего про человека, молчаливый отказ.
 *
 * Игру не «прочитывают»: уйти можно с начала, из первого боя, после серии
 * смертей и после победы — и это разные вещи. Одни просмотры не говорят
 * ничего; сравнить «начал» с «дошёл» уже говорит всё.
 *
 * В события не уходит ничего про игрока: ни имён, ни того, что он написал
 * про себя. Только числа о прохождении.
 *
 * Обёртка глохнет молча. Счётчика может не быть вовсе — на localhost, при
 * блокировщике, при отложенной загрузке скрипта, — и ронять из-за этого
 * кадр он права не имеет.
 */

/**
 * Проверочные прогоны не должны оседать в боевых данных: иначе за месяц
 * половина статистики окажется нашей. Всё, что запущено не с боевого
 * адреса, помечается заметным префиксом и отфильтровывается.
 */
const LIVE = typeof location !== 'undefined' && location.hostname === 'aka-gst.ru';
const PREFIX = LIVE ? '' : 'test-';

export function pulse(event, data = {}) {
    try {
        window.umami?.track(PREFIX + event, { game: 'neon-claw', ...data });
    } catch {
        // Счётчик — не часть игры. Его отсутствие ничего не значит.
    }
}
