/**
 * Уровень: карта в ASCII и запросы к ней.
 *
 * Карта нарисована руками, а не сгенерирована, и это осознанно. Плотность —
 * половина обаяния платформера: провал шириной ровно в три тайка, карниз
 * ровно на волосок выше прыжка, тайник, до которого надо догадаться лезть.
 * Такие вещи не выпадают из шума, их ставят по одной.
 *
 * Легенда:
 *   .  пусто            #  камень
 *   =  помост (проходится снизу, с него можно спрыгнуть вниз)
 *   o  чип              *  ядро (тайник)
 *   p  старт            e  корсар           X  точка эвакуации
 *
 * Вертикаль читается так: прыжок берёт два тайла, зацеп — три. Всё, что
 * выше двух, — это приглашение поймать кромку.
 */

import { TILE } from './tuning.js';

export const AIR = 0;
export const SOLID = 1;
export const ONEWAY = 2;

const MAP = [
    '........................................................................',
    '........................................................................',
    '........................................................................',
    '........................................................................',
    '........................................................................',
    '........................................................................',
    '........................................................................',
    '........................................................................',
    '........................................................................',
    '........................................................................',
    '........................................................................',
    '...............................................*........................',
    '..............................................####......................',
    '..............................................####......................',
    '....................................................o....o..............',
    '..................................................####=====.............',
    '......................................................##................',
    '..............................................o.......##................',
    '.............................................####.....##................',
    '......................................................##................',
    '...................................................o..##................',
    '..................................................######................',
    '...................................o.e................##................',
    '................................######.........o......##......o.........',
    '...............o.......o........######........####....##.....====.......',
    '...p.o...o.................o....######...e............##..........e...X.',
    '##############...#####...###############################################',
    '##############...#####...###############################################',
    '##############...#####...###############################################',
    '##############...#####...###############################################',
];

const KIND = { '#': SOLID, '=': ONEWAY };

/**
 * Разбор карты. Метки существ и добра превращаются в список объектов и
 * оставляют после себя воздух — в сетке остаётся только геометрия.
 */
export function parseLevel(rows = MAP) {
    const height = rows.length;
    const width = Math.max(...rows.map((r) => r.length));
    const tiles = new Uint8Array(width * height);
    const enemies = [];
    const loot = [];
    let spawn = { x: TILE * 2, y: TILE * 2 };
    let exit = null;

    for (let row = 0; row < height; row += 1) {
        for (let col = 0; col < width; col += 1) {
            const ch = rows[row][col] ?? '.';
            const at = { x: col * TILE + TILE / 2, y: row * TILE + TILE / 2 };
            if (KIND[ch] !== undefined) tiles[row * width + col] = KIND[ch];
            else if (ch === 'p') spawn = { x: at.x, y: (row + 1) * TILE };
            else if (ch === 'e') enemies.push({ x: at.x, y: (row + 1) * TILE });
            else if (ch === 'o') loot.push({ ...at, kind: 'chip' });
            else if (ch === '*') loot.push({ ...at, kind: 'core' });
            else if (ch === 'X') exit = { x: at.x, y: (row + 1) * TILE };
        }
    }

    return { width, height, tiles, spawn, enemies, loot, exit, rows };
}

/**
 * Тайл по координатам сетки.
 *
 * Слева и справа мир заканчивается камнем: уровень — это ущелье, а не
 * бесконечная плоскость, и упереться в край честнее, чем улететь за него.
 * Снизу — пустота: падение туда засчитывается как падение.
 */
export function tileAt(level, col, row) {
    if (col < 0 || col >= level.width) return SOLID;
    if (row < 0 || row >= level.height) return AIR;
    return level.tiles[row * level.width + col];
}

export const colAt = (x) => Math.floor(x / TILE);
export const rowAt = (y) => Math.floor(y / TILE);

/** Есть ли камень в точке мира. Помосты здесь не считаются: они односторонние. */
export function solidAtPoint(level, x, y) {
    return tileAt(level, colAt(x), rowAt(y)) === SOLID;
}

/** Пересекает ли прямоугольник камень. */
export function solidInRect(level, x, y, w, h) {
    const c0 = colAt(x);
    const c1 = colAt(x + w - 0.001);
    const r0 = rowAt(y);
    const r1 = rowAt(y + h - 0.001);
    for (let row = r0; row <= r1; row += 1) {
        for (let col = c0; col <= c1; col += 1) {
            if (tileAt(level, col, row) === SOLID) return true;
        }
    }
    return false;
}

export const levelPixelWidth = (level) => level.width * TILE;
export const levelPixelHeight = (level) => level.height * TILE;

export { MAP };
