/**
 * Модель игрока для замеров — одна на всех и замороженная.
 *
 * Заведена по просьбе приёмки и по важной причине: если каждый пишет
 * своего водителя, разница версий игры смешивается с разницей водителей, и
 * число перестаёт быть про игру. Правится только вместе с перезамером
 * всего, что на ней стоит.
 *
 * Игру не трогает: ничем отсюда не пользуется ни один игровой модуль,
 * файл грузится по требованию (`await import('/claw/src/driver.js')`).
 *
 * Умеет то, без чего до первого боя не дойти: прыгать над обрывом, брать
 * уступ зацепом и подтягиваться, отталкиваться от стены. Без зацепа
 * водитель встаёт у стены на 760 и меряет стену, а не игру.
 */

import { footingAt, solidAtPoint } from './level.js';
import { PLAYER, SWORD } from './tuning.js';

const NO_INPUT = {
    left: false, right: false, up: false, down: false,
    jumpHeld: false, jumpDown: false, attackDown: false, dashDown: false,
    bowHeld: false, aimX: 0, aimY: 0, swapDown: false, bladeIndex: null,
};

/** Стена прямо по курсу — во всю высоту тела, а не по одной точке. */
function wallAhead(level, body, dir) {
    const x = body.x + dir * (PLAYER.w / 2 + 4);
    for (let dy = -PLAYER.h + 4; dy < -2; dy += 6) {
        if (solidAtPoint(level, x, body.y + dy)) return true;
    }
    return false;
}

/** Обрыв прямо по курсу. */
const gapAhead = (level, body, dir) => !footingAt(level, body.x + dir * 18, body.y + 2);

/**
 * Одно решение водителя. `dir` — куда он держит путь (+1 вправо).
 * Возвращает намерение, готовое для `stepWorld`.
 */
export function drive(world, dir = 1) {
    const p = world.player;
    const b = p.body;
    const вперёд = dir > 0 ? { right: true } : { left: true };

    // Висит на уступе — подтянуться.
    if (p.state === 'hang') return { ...NO_INPUT, up: true };

    // На стене — оттолкнуться вверх и вперёд.
    if (p.state === 'wall') return { ...NO_INPUT, ...вперёд, jumpDown: true, jumpHeld: true };

    // Враг в досягаемости: верный клинок, удар вне гарды.
    const цель = world.enemies.find((e) => e.state !== 'dead'
        && Math.abs(e.body.x - b.x) < SWORD.reach - 4
        && Math.abs(e.body.y - b.y) < 20);
    if (цель) {
        return {
            ...NO_INPUT,
            bladeIndex: цель.element === 'heat' ? 1 : 0,   // 0 — жар, 1 — лёд
            attackDown: p.attack.phase === 'none' && цель.state !== 'guard',
            jumpHeld: false,
        };
    }

    // Стена по курсу — прыжок к ней: дальше сработает зацеп.
    if (b.onGround && wallAhead(world.level, b, dir)) {
        return { ...NO_INPUT, ...вперёд, jumpDown: true, jumpHeld: true };
    }

    // Обрыв по курсу — прыжок через него.
    if (b.onGround && gapAhead(world.level, b, dir)) {
        return { ...NO_INPUT, ...вперёд, jumpDown: true, jumpHeld: true };
    }

    return { ...NO_INPUT, ...вперёд, jumpHeld: !b.onGround };
}

/**
 * Тихий водитель: тот же набор возможностей, другое РЕШЕНИЕ.
 *
 * Спецификация приёмки, соблюдена по пунктам:
 *  · те же клавиши, тот же шаг, та же дальность удара — отличается только
 *    выбор, а не сила;
 *  · видит то же, что человек: где страж, куда повёрнут, как далеко, поднята
 *    ли гарда (дуга нарисована на экране) и жив ли. В `alert`, `hp` и
 *    внутренние таймеры НЕ заглядывает — иначе померим телепата;
 *  · правило одно: страж повёрнут прочь и дальше слепой зоны — подходить
 *    сзади и бить в окне между `blind` и досягаемостью клинка. Повёрнут к
 *    нам — вести себя как первый водитель, напролом. Засад и ожиданий
 *    разворота нет: ждущий бот померит терпение, а не конус.
 *
 * Считает не только успехи. Цена приёма — половина ответа: если снятий
 * много, а попыток вдвое больше, приём выглядит доступным, а на деле
 * капризный. Попытка считается проваленной, когда страж довернулся к нам —
 * ровно то, что видит человек.
 */
/**
 * ВНИМАНИЕ: тихий водитель ПОКА НЕ РАБОТАЕТ, числами пользоваться нельзя.
 *
 * Замерено 6 сентября, по сорок прогонов на сборку:
 *
 *   напролом · конус          медиана тайл 53.7 · снятий 0
 *   тихий    · конус          медиана тайл 53.7 · снятий 0 · попыток 280 · сорвалось 80
 *   напролом · старое зрение  медиана тайл 53.7 · снятий 0
 *   тихий    · старое зрение  медиана тайл 53.7 · снятий 0 · попыток 240 · сорвалось 40
 *
 * Он ВХОДИТ в окно удара — одиннадцать шагов за прогон, ближе всего 23 при
 * окне 14…26, — и не выполняет приём ни разу. Окно живёт примерно столько
 * же, сколько длится замах (0,09 с), и страж в патруле успевает уйти;
 * попытка держаться за целью во время замаха не помогла.
 *
 * Пока снятий ноль в ОБЕИХ сборках, сравнение не различает ничего, и вывод
 * «конус ничего не даёт» из этих чисел делать нельзя: это свойство
 * водителя, а не игры. Чинить надо конверсию попытки в удар.
 */
export function createQuietDriver() {
    const stats = { попыток: 0, сорвалось: 0, снятий: 0 };
    let цельId = null;

    const step = (world, dir = 1) => {
        const p = world.player;
        const b = p.body;

        const живой = world.enemies
            .filter((e) => e.state !== 'dead' && Math.abs(e.body.y - b.y) < 24)
            .sort((a, c) => Math.abs(a.body.x - b.x) - Math.abs(c.body.x - b.x))[0];

        if (!живой) {
            цельId = null;
            return drive(world, dir);
        }

        const dx = живой.body.x - b.x;
        const сзади = Math.sign(dx) === живой.facing;   // мы позади: он смотрит прочь
        const разрыв = Math.abs(dx);

        // Попытка сорвалась: страж довернулся к нам. Видно человеку.
        if (цельId === живой.id && !сзади) {
            stats.сорвалось += 1;
            цельId = null;
        }

        if (!сзади) return drive(world, dir);

        if (цельId !== живой.id) {
            stats.попыток += 1;
            цельId = живой.id;
        }

        const кСтражу = dx > 0 ? { right: true } : { left: true };

        // В окне между слепой зоной и клинком — бить.
        if (разрыв <= SWORD.reach - 4) {
            // Держаться за целью и во время замаха. Стоящий на месте не
            // успевает: окно живёт ровно столько, сколько длится замах
            // (0,09 с), а страж в патруле за это время уходит. Замерено:
            // одиннадцать шагов в окне за весь прогон и ноль снятий.
            stats.снятий = world.takedowns;
            return {
                ...NO_INPUT,
                ...кСтражу,
                bladeIndex: живой.element === 'heat' ? 1 : 0,
                attackDown: p.attack.phase === 'none' && живой.state !== 'guard',
            };
        }

        // Ещё далеко — подходить, повторяя проходимость первого водителя.
        const подход = drive(world, dx > 0 ? 1 : -1);
        return { ...подход, ...кСтражу, right: dx > 0, left: dx < 0 };
    };

    return { step, stats };
}
