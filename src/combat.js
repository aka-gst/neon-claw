/**
 * Правила боя. Дуэль на мечах, как в Captain Claw.
 *
 * Игра начиналась платформером с фехтованием, потом ушла в стелс и
 * вернулась обратно. Стелс со всей его начинкой — зрением, слухом,
 * светом — передан соседней игре (см. `docs/stealth-handover.md`), а
 * здесь остался бой, ради которого всё затевалось.
 *
 * Ошибка стоит дёшево: пять жизней и мгновенный откат к чекпоинту.
 * Платформер про исследование не должен наказывать за любопытство —
 * наказывать он должен за небрежность в бою, и для этого есть гарда.
 *
 * Гарда и есть весь бой. Страж закрывается после каждого попадания, и
 * каждый удар в поднятую гарду её продлевает: долбить кнопку становится
 * строго хуже, чем выждать. Зато после того как гарда падает, он какое-то
 * время не может закрыться снова, и выждавший успевает добить.
 */

export const RULES = {
    player: { hp: 5, retry: 'checkpoint' },
    enemy: { hp: 3, guard: 'meter', parry: false },
};

/** Раскрыт ли страж — то есть занят ли он собственной атакой. */
export const OPEN_STATES = new Set(['windup', 'active', 'recover']);
export const isOpen = (enemy) => OPEN_STATES.has(enemy.state);
