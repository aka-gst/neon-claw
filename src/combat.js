/**
 * Правила боя. Один набор — тот, что выиграл сравнение.
 *
 * Их было четыре, и они переключались на ходу: дуэль как в Клоу (пять
 * жизней, страж держит три удара), однохитовое «Лезвие» как в Katana Zero,
 * «Тень» как в Tenchu и смесь. Смесь выиграла, остальные убраны — выбор
 * сложности в игре, у которой ещё нет своей сложности, только размывает
 * то, ради чего всё делается.
 *
 * Что осталось от сравнения:
 *
 *   Одна ошибка прощается, вторая нет. Двух жизней хватает, чтобы
 *   промах не заканчивал забег, и мало, чтобы бить наугад.
 *
 *   Со спины и сверху — сразу. Заход в правильную точку отменяет бой,
 *   а не выигрывает его: в этом вся разница между стелсом и дракой.
 *
 *   В лоб — вдвое дольше и очень громко. Лобовая стычка возможна, но
 *   звон о гарду слышно на весь сектор, и за него приходит вся смена.
 *
 *   Смерть не заканчивает забег: короткая пауза, чтобы игрок увидел,
 *   что его убило, — и он на последнем чекпоинте, стражи подняты.
 *   Комната становится задачей, а не проверкой на живучесть.
 */

export const RULES = {
    player: { hp: 2, retry: 'checkpoint' },
    enemy: { hp: 2, guard: 'meter', parry: false },
    takedown: { back: true, above: true },
};

/**
 * Как именно пришёл удар. Со спины — если оба смотрят в одну сторону:
 * значит, герой зашёл сзади. Сверху — если он в воздухе и выше головы.
 */
export function strikeKind(player, enemy) {
    const above = !player.body.onGround
        && player.body.y <= enemy.body.y - enemy.body.h * 0.55;
    if (above) return 'above';
    if (player.facing === enemy.facing) return 'back';
    return 'front';
}

/** Раскрыт ли страж — то есть занят ли он собственной атакой. */
export const OPEN_STATES = new Set(['windup', 'active', 'recover']);
export const isOpen = (enemy) => OPEN_STATES.has(enemy.state);
