/**
 * Подпись в кадре. Оператор снимал крупный план для витрины и уткнулся:
 * подпись рисовалась во всю ширину холста и срезалась по обоим краям —
 * «...аскол» слева, «добивай...» справа. Читается как брак вёрстки, и
 * задевает не только съёмку: то же увидит любой, кто сделает скриншот.
 *
 * Настоящую ширину меряет только браузер (шрифт), и я померил там:
 * «Раскол! Гарда не встанет.» — 192 точки, «Гарда. Дуга тает…» — 221 и
 * 158 двумя строками, при кадре в 264. Здесь проверяется сама разбивка.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

import { wrapText } from '../src/render.js';

/** Поддельный измеритель: десять точек на символ, считать легко в уме. */
const ctx = { measureText: (s) => ({ width: s.length * 10 }) };

test('длинная подпись переносится по словам и не вылезает за предел', () => {
    const lines = wrapText(ctx, 'один два три четыре пять шесть', 100);
    assert.ok(lines.length > 1, 'не перенеслась вовсе');
    for (const line of lines) {
        assert.ok(line.length * 10 <= 100, `строка «${line}» шире предела`);
    }
    assert.equal(lines.join(' '), 'один два три четыре пять шесть', 'потеряли слова');
});

test('короткая подпись остаётся одной строкой', () => {
    assert.deepEqual(wrapText(ctx, 'коротко', 100), ['коротко']);
});

test('слово длиннее предела не режется посередине', () => {
    // Обрезать слово хуже, чем дать ему вылезти: обрезок нечитаем вовсе.
    const lines = wrapText(ctx, 'этослишкомдлинноесловоцеликом', 100);
    assert.deepEqual(lines, ['этослишкомдлинноесловоцеликом']);
});

test('предел взят с запасом под крупный план, а не под весь холст', () => {
    const src = readFileSync(new URL('../src/render.js', import.meta.url), 'utf8');
    // Кадр для витрины берёт 55% ширины; предел обязан быть уже.
    const m = src.match(/wrapText\(ctx, world\.notice\.text, VIEW\.w \* ([\d.]+)\)/);
    assert.ok(m, 'подпись больше не переносится');
    assert.ok(Number(m[1]) <= 0.55, `предел ${m[1]} — шире кадра витрины`);
});
